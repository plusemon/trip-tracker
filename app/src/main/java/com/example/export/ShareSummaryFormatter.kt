package com.example.export

import com.example.data.entity.ExpenseEntity
import com.example.data.entity.PayerType
import com.example.data.entity.TripEntity
import com.example.domain.model.CurrencyFormatter
import com.example.domain.model.MemberBalance
import com.example.domain.model.SettlementTransaction
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object ShareSummaryFormatter {

    fun generateWhatsAppText(
        trip: TripEntity,
        balances: List<MemberBalance>,
        settlements: List<SettlementTransaction>,
        expenses: List<ExpenseEntity>,
        totalDeposits: Double,
        commonFundSpent: Double,
        remainingCommonFund: Double
    ): String {
        val dateFormat = SimpleDateFormat("dd MMM yyyy", Locale.US)
        val startStr = dateFormat.format(Date(trip.startDate))
        val endStr = dateFormat.format(Date(trip.endDate))
        val totalSpentOverall = expenses.sumOf { it.amount }

        val sb = StringBuilder()
        sb.appendLine("🇧🇩 *TRIPSPLIT BD - TOUR SETTLEMENT SUMMARY* 🇧🇩")
        sb.appendLine("━━━━━━━━━━━━━━━━━━━━━━━━━")
        sb.appendLine("📍 *Trip:* ${trip.name}")
        sb.appendLine("🗺️ *Destination:* ${trip.destination}")
        sb.appendLine("🗓️ *Dates:* $startStr - $endStr")
        sb.appendLine("👤 *Tour Lead:* ${trip.managerName}")
        sb.appendLine("━━━━━━━━━━━━━━━━━━━━━━━━━")
        sb.appendLine()

        sb.appendLine("💰 *GROUP FUND BALANCE*")
        sb.appendLine("• Total Collected: ${CurrencyFormatter.formatTaka(totalDeposits, trip.currencySymbol)}")
        sb.appendLine("• Paid from Group Fund: ${CurrencyFormatter.formatTaka(commonFundSpent, trip.currencySymbol)}")
        val fundStatus = if (remainingCommonFund >= 0) "Cash in Hand" else "Deficit"
        sb.appendLine("• Remaining Balance: ${CurrencyFormatter.formatTaka(remainingCommonFund, trip.currencySymbol)} ($fundStatus)")
        sb.appendLine("• Total Trip Expenses: ${CurrencyFormatter.formatTaka(totalSpentOverall, trip.currencySymbol)}")
        sb.appendLine()

        sb.appendLine("📊 *INDIVIDUAL MEMBER LEDGERS*")
        for (mb in balances) {
            val netStr = when {
                mb.isCreditor -> "🟢 Gets Back: ${CurrencyFormatter.formatTaka(mb.netBalance, trip.currencySymbol)}"
                mb.isDebtor -> "🔴 Owes: ${CurrencyFormatter.formatTaka(kotlin.math.abs(mb.netBalance), trip.currencySymbol)}"
                else -> "⚪ Balanced"
            }
            sb.appendLine("• *${mb.member.name}*")
            sb.appendLine("   - Deposited: ${CurrencyFormatter.formatTaka(mb.totalDeposited, trip.currencySymbol)}")
            if (mb.totalPocketPaid > 0) {
                sb.appendLine("   - Out-of-Pocket Paid: ${CurrencyFormatter.formatTaka(mb.totalPocketPaid, trip.currencySymbol)}")
            }
            sb.appendLine("   - Share Consumed: ${CurrencyFormatter.formatTaka(mb.totalConsumed, trip.currencySymbol)}")
            sb.appendLine("   - $netStr")
        }
        sb.appendLine()

        sb.appendLine("🤝 *MINIMIZED SETTLEMENT STEPS*")
        if (settlements.isEmpty()) {
            sb.appendLine("🎉 All accounts are balanced! No pending debts.")
        } else {
            settlements.forEachIndexed { index, st ->
                sb.appendLine("${index + 1}. *${st.fromMemberName}* ➡️ pays *${CurrencyFormatter.formatTaka(st.amount, trip.currencySymbol)}* to *${st.toMemberName}*")
            }
        }
        sb.appendLine()

        sb.appendLine("━━━━━━━━━━━━━━━━━━━━━━━━━")
        sb.appendLine("Generated by Trip Tracker | Offline Group Wallet")

        return sb.toString()
    }
}
